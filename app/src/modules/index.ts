import { ModuleRegistry } from './registry';
import { primitives } from './primitives';
import { installComposites } from './composites';
import { calculationModules } from './calculation';
import { containerInputs } from './containers';
import { indexingModules } from './indexing';
import { calculationGroup } from './calculationGroup';
import { dimensionModules } from './dimensions';
import { localParameter } from './localParameter';
import { tensorVariable } from './tensorVariable';
export const registry = new ModuleRegistry();
primitives.forEach((def) => registry.register(def));
containerInputs.forEach((def) => registry.register(def));
calculationModules.forEach((def) => registry.register(def));
indexingModules.forEach((def) => registry.register(def));
dimensionModules.forEach((def) => registry.register(def));
registry.register(localParameter);
registry.register(tensorVariable);
registry.register(calculationGroup);
installComposites(registry);
